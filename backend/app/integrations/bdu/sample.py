def thrlist_xlsx(revision: int = 1) -> bytes:
    rows: list[list[object]] = [[f"Перечень угроз безопасности информации. {SAMPLE_NOTE}"]]
    rows.append(THREAT_HEADER)
    changed = "15.07.2025" if revision == 1 else "20.10.2026"
    for n, title, desc, src, target, c, i, a in _THREATS:
        if revision == 2 and n == 170:
            desc += " Дополнено: шифрование резервных копий."
        rows.append([n, title, desc, src, target, c, i, a, "10.03.2015",
                     changed if (revision == 2 and n == 170) else "15.07.2025"])  # fmt: skip
    if revision == 2:
        rows.append([
            222, "Угроза подмены обновлений программного обеспечения",
            "Угроза заключается в возможности подмены нарушителем пакетов обновлений.",
            "Внешний нарушитель со средним потенциалом", "Системное программное обеспечение",
            0, 1, 1, "20.10.2026", changed,
        ])  # fmt: skip
    return write_xlsx(rows, modified="2026-11-01T09:00:00Z")


